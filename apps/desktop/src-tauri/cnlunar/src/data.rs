#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_lengths() {
        assert_eq!(LUNAR_NEW_YEAR.len(), 200);
        assert_eq!(
            LUNAR_MONTH_DATA.len(),
            (LUNAR_END_YEAR - START_YEAR + 1) as usize
        );
        assert_eq!(SOLAR_TERMS_DATA.len(), 200);
        assert_eq!(TERM_MIN_DAY.len(), 24);
    }

    #[test]
    fn decodes_chinese_new_year() {
        let cny = |year: i32| {
            let v = LUNAR_NEW_YEAR[(year - START_YEAR) as usize];
            ((v >> 5) & 0x3, v & 0x1f)
        };
        assert_eq!(cny(1901), (2, 19));
        assert_eq!(cny(2023), (1, 22));
        assert_eq!(cny(2025), (1, 29));
        assert_eq!(cny(2026), (2, 17));
        assert_eq!(cny(2100), (2, 9));
    }

    #[test]
    fn decodes_leap_month_info() {
        let info = |year: i32| {
            let v = LUNAR_MONTH_DATA[(year - START_YEAR) as usize];
            ((v >> 13) & 0xf, 29 + ((v >> 12) & 1) as u8)
        };
        assert_eq!(info(2023), (2, 29)); // 闰二月
        assert_eq!(info(2025), (6, 29)); // 闰六月
        assert_eq!(info(2026), (0, 29)); // 无闰月
    }

    #[test]
    fn decodes_solar_term_days() {
        let term_day = |year: i32, t: usize| {
            let data = SOLAR_TERMS_DATA[(year - START_YEAR) as usize];
            (((data >> (2 * t)) & 3) as u8) + TERM_MIN_DAY[t]
        };
        // 节气 t 落在月 t/2+1
        assert_eq!(term_day(2025, 6), 4); // 2025 清明 4/4
        assert_eq!(term_day(2026, 6), 5); // 2026 清明 4/5
        assert_eq!(term_day(2026, 23), 22); // 2026 冬至 12/22
    }
}
